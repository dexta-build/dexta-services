#!/usr/bin/env node
/**
 * Team profiles live at the top level (/daniel-azu), so every address the
 * site uses itself must be off-limits to them. This script finds those
 * addresses in the code and writes them to
 * src/lib/team/site-pages.generated.ts. It runs before `pnpm dev` and
 * `pnpm build`, so a new top-level page, public folder or redirect is
 * reserved automatically; nothing is maintained by hand.
 *
 * It finds:
 *  - top-level folders of src/app (looking inside route groups like (public))
 *  - metadata routes at the top level (robots, sitemap, opengraph-image…)
 *  - folders in public/
 *  - redirect/rewrite sources in next.config.ts
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();
const out = join(root, "src/lib/team/site-pages.generated.ts");

const found = new Map(); // address → where it comes from

function scanApp(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const name = entry.name;
    const where = relative(root, join(dir, name)).replace(/\\/g, "/");
    if (entry.isDirectory()) {
      if (/^\(.*\)$/.test(name))
        scanApp(join(dir, name)); // route group
      else if (!/^[[_@.]/.test(name)) found.set(name.toLowerCase(), where);
    } else {
      const m = name.match(
        /^(robots|sitemap|opengraph-image|twitter-image|icon|apple-icon|manifest)\./,
      );
      if (m) found.set(m[1], where);
    }
  }
}
scanApp(join(root, "src/app"));

if (existsSync(join(root, "public")))
  for (const entry of readdirSync(join(root, "public"), {
    withFileTypes: true,
  }))
    if (entry.isDirectory())
      found.set(entry.name.toLowerCase(), `public/${entry.name}`);

for (const file of ["next.config.ts", "next.config.mjs", "next.config.js"]) {
  if (!existsSync(join(root, file))) continue;
  const config = readFileSync(join(root, file), "utf8");
  for (const m of config.matchAll(/source:\s*["'`]\/([A-Za-z0-9-]+)/g))
    found.set(m[1].toLowerCase(), `${file} (redirect)`);
}

const names = [...found.keys()].sort();
const body = `// Generated by scripts/generate-site-pages.mjs before \`pnpm dev\` and
// \`pnpm build\`. Do not edit: add or remove pages and this follows.
//
// Every top-level address the site uses itself. Team profiles (/daniel-azu)
// can't take these (see src/lib/team/addresses.ts).

export const DETECTED_SITE_PAGES = [
${names.map((n) => `  ${JSON.stringify(n)}, // ${found.get(n)}`).join("\n")}
] as const;
`;

const before = existsSync(out) ? readFileSync(out, "utf8") : "";
if (before === body) {
  console.log(`✓ Site pages: ${names.length} top-level addresses (unchanged).`);
} else {
  const old = new Set(
    [...before.matchAll(/^\s+"([^"]+)",/gm)].map((m) => m[1]),
  );
  const added = names.filter((n) => !old.has(n));
  const removed = [...old].filter((n) => !found.has(n));
  writeFileSync(out, body);
  console.log(
    `✓ Site pages: ${names.length} top-level addresses reserved for the site` +
      (added.length ? ` · added ${added.join(", ")}` : "") +
      (removed.length ? ` · removed ${removed.join(", ")}` : ""),
  );
}
